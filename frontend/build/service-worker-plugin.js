/**
 * build/service-worker-plugin.js — replace the service worker chen's PWA
 * plugin generates.
 *
 * chen emits a sw.js that is cache-first for EVERY request, keyed on a cache
 * name that is the constant 'chen-pwa-v1'
 * (node_modules/chen-the-dawnstreak/dist/vite-plugin/index.js). Three things
 * follow from that, and the third is fatal:
 *
 *   1. `caches.match(req).then(r => r || fetch(req))` means a cached response
 *      always wins. Nothing revalidates, ever.
 *   2. The activate handler purges caches whose name !== CACHE_NAME. Since the
 *      name never changes between builds, that predicate is never true and no
 *      cache is ever evicted.
 *   3. install pre-caches '/', so index.html — the one file that must never be
 *      cached hard, because it is what points at the content-hashed bundles —
 *      is pinned on the very first visit.
 *
 * Net effect: a returning visitor is served the index.html from whenever they
 * first loaded the site, forever, along with the asset graph it references.
 * They never receive another deploy. That is how a fixed favicon, or any other
 * change, can ship correctly and still never reach anyone.
 *
 * This plugin overwrites that file with a worker that splits the two cases the
 * bundle actually has:
 *
 *   - /assets/* is content-hashed, so a hit is always valid → cache-first.
 *   - Everything else (navigations, the manifest, brand files at stable names)
 *     → network-first with a cache fallback, so the app still opens offline but
 *     a reachable network always wins.
 *
 * The cache name embeds a build fingerprint, so `activate` genuinely evicts the
 * previous build, and skipWaiting + clients.claim mean the new worker takes
 * over on the next load rather than the load after that.
 *
 * Must be registered AFTER ...chen() in nasti.config.ts — both write in
 * closeBundle, and the last write wins.
 */

// @ts-nocheck — plain JS build helper, run by node outside the app's tsconfig.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

/** Fingerprint the build from its emitted asset names. Content-hashed
 *  filenames change exactly when the build's output changes, so this is stable
 *  across identical rebuilds (unlike a timestamp) and differs across deploys. */
function buildFingerprint(distDir) {
  const assetsDir = path.join(distDir, "assets");
  let names = [];
  try {
    names = fs.readdirSync(assetsDir).sort();
  } catch {
    /* no assets dir — fall through to hashing index.html alone */
  }
  const h = crypto.createHash("sha256");
  for (const n of names) h.update(n);
  try {
    h.update(fs.readFileSync(path.join(distDir, "index.html")));
  } catch {
    /* index.html always exists in practice; tolerate its absence */
  }
  return h.digest("hex").slice(0, 12);
}

function workerSource(version) {
  return `// Generated by build/service-worker-plugin.js — do not edit by hand.
const CACHE = 'wuling-${version}';

// Content-hashed bundles only. A hit is valid by construction: the name
// changes whenever the bytes do.
const IMMUTABLE = /^\\/assets\\//;

self.addEventListener('install', (event) => {
  // Take over as soon as this worker is installed rather than waiting for
  // every tab holding the previous one to close.
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // CACHE carries a build fingerprint, so this actually evicts prior builds.
    const names = await caches.keys();
    await Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  // Never mediate cross-origin, and never cache the API — a stale API response
  // served to an authenticated user is worse than an offline error.
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return;
  // /help/* is server-rendered and changes without a new SW — always network.
  if (url.pathname === '/help' || url.pathname.startsWith('/help/')) return;

  if (IMMUTABLE.test(url.pathname)) {
    event.respondWith((async () => {
      const hit = await caches.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res && res.status === 200 && res.type === 'basic') {
        const copy = res.clone();
        (await caches.open(CACHE)).put(req, copy);
      }
      return res;
    })());
    return;
  }

  // Everything else: network first, cache only as an offline fallback.
  event.respondWith((async () => {
    try {
      const res = await fetch(req);
      if (res && res.status === 200 && res.type === 'basic') {
        const cache = await caches.open(CACHE);
        cache.put(req, res.clone());
        // Navigations serve the SPA shell. Also store it under the canonical
        // /index.html key so offline fallbacks for unvisited routes work.
        if (req.mode === 'navigate') {
          cache.put('/index.html', res.clone());
        }
      }
      return res;
    } catch (err) {
      const hit = await caches.match(req);
      if (hit) return hit;
      // A navigation with nothing cached for that exact URL still needs an
      // entry document. The SPA is served by rewriting every unknown path to
      // index.html, so a previous visit may have cached it under '/' or under
      // whatever deep link the user first landed on — try both spellings.
      if (req.mode === 'navigate') {
        const shell = (await caches.match('/index.html')) || (await caches.match('/'));
        if (shell) return shell;
      }
      throw err;
    }
  })());
});
`;
}

export function serviceWorkerPlugin() {
  const root = process.cwd();
  const distDir = path.resolve(root, "dist");
  return {
    name: "wuling-service-worker",
    closeBundle() {
      const swPath = path.join(distDir, "sw.js");
      if (!fs.existsSync(distDir)) return;
      fs.writeFileSync(swPath, workerSource(buildFingerprint(distDir)), "utf8");
    },
  };
}
